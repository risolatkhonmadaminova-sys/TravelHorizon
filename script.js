const languageSelect = document.querySelector("#language-select");
const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");
let activeLanguage = "en";

function translate(key) {
  return translations[activeLanguage][key] ?? translations.en[key] ?? key;
}

function setLanguage(language) {
  activeLanguage = translations[language] ? language : "en";
  document.documentElement.lang = activeLanguage;
  if (languageSelect) languageSelect.value = activeLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translate(element.dataset.i18n);
    if (element.hasAttribute("data-i18n-html")) {
      element.innerHTML = value;
    } else if (element instanceof HTMLMetaElement) {
      element.content = value;
    } else {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute(
      "placeholder",
      translate(element.dataset.i18nPlaceholder),
    );
  });

  const page = document.body.dataset.page || "home";
  document.title = translate(`site.${page}.title`);
  if (menuToggle) {
    const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute(
      "aria-label",
      translate(isExpanded ? "menu.close" : "menu.open"),
    );
  }
  updateTourCount();
  updateBookingQuote();
}

const page = document.body.dataset.page || "home";
document
  .querySelector(`[data-page-link="${page}"]`)
  ?.setAttribute("aria-current", "page");

menuToggle?.addEventListener("click", () => {
  const isExpanded = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isExpanded));
  menuToggle.setAttribute(
    "aria-label",
    translate(isExpanded ? "menu.open" : "menu.close"),
  );
  mainNav?.classList.toggle("is-open", !isExpanded);
});

mainNav?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    menuToggle?.setAttribute("aria-expanded", "false");
    if (menuToggle)
      menuToggle.setAttribute("aria-label", translate("menu.open"));
    mainNav.classList.remove("is-open");
  });
});

const tourFilters = [...document.querySelectorAll("[data-tour-filter]")];
const tourCards = [...document.querySelectorAll(".tour-card")];
const tourEmptyState = document.querySelector(".tour-list .empty-state");
const resultsCount = document.querySelector(".tour-list .results-count");
let activeFilter = "all";

function updateTourCount(
  count = tourCards.filter((card) => !card.hidden).length,
) {
  if (!resultsCount) return;
  const label =
    activeLanguage === "ru"
      ? count % 10 === 1 && count % 100 !== 11
        ? "тур"
        : count % 10 >= 2 &&
            count % 10 <= 4 &&
            (count % 100 < 12 || count % 100 > 14)
          ? "тура"
          : "туров"
      : activeLanguage === "ky"
        ? "сапар"
        : count === 1
          ? "tour"
          : "tours";
  resultsCount.textContent = `${String(count).padStart(2, "0")} ${label}`;
}

function filterTours() {
  let visibleCount = 0;
  tourCards.forEach((card) => {
    const isVisible =
      activeFilter === "all" ||
      card.dataset.tags.split(" ").includes(activeFilter);
    card.hidden = !isVisible;
    if (isVisible) visibleCount += 1;
  });
  if (tourEmptyState) tourEmptyState.hidden = visibleCount > 0;
  updateTourCount(visibleCount);
}

tourFilters.forEach((button) => {
  button.addEventListener("click", () => {
    activeFilter = button.dataset.tourFilter;
    tourFilters.forEach((filterButton) => {
      const selected = filterButton === button;
      filterButton.classList.toggle("is-active", selected);
      filterButton.setAttribute("aria-pressed", String(selected));
    });
    filterTours();
  });
});

