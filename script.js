function normalizeContentOverrides(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new Error("The backup must contain a language object.");
  }

  const normalized = {};
  for (const [language, entries] of Object.entries(value)) {
    if (
      !Object.hasOwn(translations, language) ||
      !entries ||
      typeof entries !== "object" ||
      Array.isArray(entries)
    ) {
      throw new Error(`Invalid content data for language "${language}".`);
    }

    normalized[language] = {};
    for (const [key, text] of Object.entries(entries)) {
      if (typeof text !== "string") {
        throw new Error(`Invalid translation entry "${language}.${key}".`);
      }
      if (!Object.hasOwn(translations[language], key)) continue;
      normalized[language][key] = text;
    }
  }
  return normalized;
}

