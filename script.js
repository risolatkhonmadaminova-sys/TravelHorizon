function getTourPrice(tourId) {
  const priceText =
    siteCatalog?.tours.find((entry) => entry.id === tourId)?.fields[
      activeLanguage
    ].price || translate(`trip.${tourId}.price`);
  const match = priceText.match(/\d[\d,]*(?:\.\d+)?/);
  if (!match) return undefined;

  const price = Number(match[0].replace(/,/g, ""));
  return Number.isFinite(price) ? price : undefined;
}

function formatUSD(amount) {
  const locale = { en: "en-US", ru: "ru-RU", ky: "ky-KG" }[activeLanguage];
  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(amount);
}

function updateBookingQuote() {
  if (!tourSelect || !travelerCount || !bookingPrice || !pricePerPerson) return;
  const count = Math.min(
    20,
    Math.max(1, Number.parseInt(travelerCount.value, 10) || 1),
  );
  travelerCount.value = String(count);
  const price = getTourPrice(tourSelect.value);

  if (!Number.isFinite(price)) {
    const quoteText = tourSelect.value ? translate("contacts.form.quote") : "—";
    bookingPrice.textContent = quoteText;
    pricePerPerson.textContent = quoteText;
    return;
  }

  pricePerPerson.textContent = formatUSD(price);
  bookingPrice.textContent = formatUSD(price * count);
}

